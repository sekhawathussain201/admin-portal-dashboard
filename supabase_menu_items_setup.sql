-- 1. Create the 'menu_items' table
CREATE TABLE IF NOT EXISTS public.menu_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    price NUMERIC NOT NULL,
    description TEXT DEFAULT '',
    image TEXT DEFAULT '',
    prep_time TEXT DEFAULT '20 mins',
    is_bestseller BOOLEAN DEFAULT false,
    is_spicy BOOLEAN DEFAULT false,
    is_available BOOLEAN DEFAULT true,
    rating NUMERIC DEFAULT 5.0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.menu_items ENABLE ROW LEVEL SECURITY;

-- 3. Policy: Allow public & admin to view all menu items
DROP POLICY IF EXISTS "Allow public to read menu_items" ON public.menu_items;
CREATE POLICY "Allow public to read menu_items"
ON public.menu_items FOR SELECT
TO anon, authenticated
USING (true);

-- 4. Policy: Allow admin to add new menu items
DROP POLICY IF EXISTS "Allow public to insert menu_items" ON public.menu_items;
CREATE POLICY "Allow public to insert menu_items"
ON public.menu_items FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- 5. Policy: Allow admin to update menu items
DROP POLICY IF EXISTS "Allow public to update menu_items" ON public.menu_items;
CREATE POLICY "Allow public to update menu_items"
ON public.menu_items FOR UPDATE
TO anon, authenticated
USING (true)
WITH CHECK (true);

-- 6. Policy: Allow admin to delete menu items
DROP POLICY IF EXISTS "Allow public to delete menu_items" ON public.menu_items;
CREATE POLICY "Allow public to delete menu_items"
ON public.menu_items FOR DELETE
TO anon, authenticated
USING (true);

